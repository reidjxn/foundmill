#!/usr/bin/env node
// The skills library's generator (WP-06 T2; founder, Nov 16, 2026: D6). The source of truth is one Markdown file per
// skill, packages/agents/skills/<category>/<key>.md, with front matter of top-level `key: value` lines and the
// instructions as the body. This script writes packages/agents/src/skill-library/catalog.generated.ts, which is
// checked in: nothing reads a Markdown file at run time, and the catalog carries each skill's full body for the app.
//
//   node scripts/build-skill-library.mjs           write the catalog
//   node scripts/build-skill-library.mjs --check   exit 1 with a one-line reason when the catalog on disk is stale
//
// It refuses (exit 1, one line): a file whose folder is not its `category`, whose name is not `<key>.md`, a repeated
// key, a missing field, CRLF line endings, or a front matter line that is not `key: value` (`default_for:` may be
// empty). A trailing ` # us-english-allow` on a value is stripped (the copy linter's marker for the enum key
// `judgement` and rated keys such as `prioritisation`).
//
// The files use the authoring spec's words (packages/agents/skills/README.md); WP-06 T3 maps them onto the library's
// fields here, and a value outside the mapping is refused: `stage` onto the product's stages, `needs` onto connectors
// (all "better with": every skill works without them) or "not yet on Foundmill", `adapted_from` and `license_note`
// onto provenance. What the generator cannot see (template keys, rated skill keys, connector keys, the notices) is
// checked by packages/agents/src/__tests__/skill-library.test.ts and by the catalog's types.
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(fileURLToPath(import.meta.url), "../..");
export const SKILLS_DIR = join(ROOT, "packages/agents/skills");
export const CATALOG_FILE = join(ROOT, "packages/agents/src/skill-library/catalog.generated.ts");
const TYPES_FILE = join(ROOT, "packages/agents/src/skill-library/types.ts");

export const HEADER = "// GENERATED by scripts/build-skill-library.mjs from packages/agents/skills. Do not edit.";
const REQUIRED = [
  "key", "name", "description", "category", "attribute_name", "attribute_group", "when_to_use", "roles", "stage", "needs",
  "adapted_from", "license_note", "improves", "version",
];
/** Fields that must be present but may be empty. */
const MAY_BE_EMPTY = ["default_for"];
/** Optional: the defaults release that first attached the skill (WP-06 T6); absent means 1. */
const ALLOW_SUFFIX = / # us-english-allow$/;
const GROUPS = ["craft", "judgement", "execution"];

/** The authoring stages, onto PRODUCT_STAGES (packages/shared), in that enum's order. */
export const PRODUCT_STAGES = ["drafting", "awaiting_signoff", "building", "selling"];
const STAGE_MAP = {
  idea: ["drafting", "awaiting_signoff"],
  building: ["building"],
  page_live: ["building", "selling"],
  first_followers: ["selling"],
  first_sale: ["selling"],
  growing: ["selling"],
};
/** The capability words, onto a connector the gateway serves, a tool Foundmill has not built, or nothing. */
const NEED_MAP = {
  web_research: { connector: "web" },
  email_send: { connector: "platform_mail" },
  social_publish: { connector: "buffer" },
  payments: { connector: "stripe" },
  repo: { connector: "github" },
  analytics: { connector: "posthog" },
  search_console: { notYet: "Search Console" },
  // No agent tool publishes a page (the founder does), so the skill's page step is the founder's.
  page_publish: {},
  none: {},
};
const SOURCE = /^[a-z0-9-]+:[a-z0-9-]+$/;
const LICENSE = /\b(MIT|Apache-2\.0)\b/;

/** SKILL_LIBRARY_CATEGORIES as written in packages/agents/src/skill-library/types.ts (one list, read from the TS). */
export function categoriesFrom(typesFile = TYPES_FILE) {
  const m = /SKILL_LIBRARY_CATEGORIES = \[([^\]]*)\] as const/.exec(readFileSync(typesFile, "utf8"));
  if (!m) throw new Error(`${relative(ROOT, typesFile)}: SKILL_LIBRARY_CATEGORIES not found`);
  return [...m[1].matchAll(/"([a-z_]+)"/g)].map((x) => x[1]);
}

/** One skill file: its front matter fields and its body (the text after the closing `---`, less the final newline). */
export function parseSkillSource(text, where) {
  if (text.includes("\r")) throw new Error(`${where}: CRLF line endings (use LF)`);
  if (!text.startsWith("---\n")) throw new Error(`${where}: no front matter (the file starts with ---)`);
  const end = text.indexOf("\n---\n", 3);
  if (end < 0) throw new Error(`${where}: front matter is not closed with ---`);
  const fields = {};
  for (const line of text.slice(4, end).split("\n")) {
    const m = /^([a-z_]+): (.+)$/.exec(line) ?? /^([a-z_]+):()$/.exec(line);
    if (!m) throw new Error(`${where}: front matter line is not \`key: value\`: ${JSON.stringify(line)}`);
    // An empty value is allowed where MAY_BE_EMPTY says so, and is otherwise a missing field (refused below).
    if (m[2] === "" && !MAY_BE_EMPTY.includes(m[1])) continue;
    if (m[1] in fields) throw new Error(`${where}: front matter repeats ${m[1]}`);
    fields[m[1]] = m[2].replace(ALLOW_SUFFIX, "").trim();
  }
  for (const f of REQUIRED) if (!fields[f]) throw new Error(`${where}: missing field ${f}`);
  for (const f of MAY_BE_EMPTY) if (!(f in fields)) throw new Error(`${where}: missing field ${f}`);
  if (fields.default_since && !/^[1-9]\d*$/.test(fields.default_since)) throw new Error(`${where}: default_since is not a whole number: ${fields.default_since}`);
  if (!/^[1-9]\d*$/.test(fields.version)) throw new Error(`${where}: version is not a whole number: ${fields.version}`);
  // Optional (WP-06 T13): the release a default arrives in (1 when absent), and `load: always` for a body that every
  // code task loads up front when the preload switch is on for it.
  if ("default_since" in fields && !/^[1-9]\d*$/.test(fields.default_since)) throw new Error(`${where}: default_since is not a whole number: ${fields.default_since}`);
  if ("load" in fields && fields.load !== "always") throw new Error(`${where}: load is not "always": ${fields.load}`);
  const body = text.slice(end + 5).replace(/\n$/, "");
  if (!body.trim()) throw new Error(`${where}: empty body`);
  return { fields, body };
}

const list = (value) => (value ? value.split(",").map((x) => x.trim()).filter(Boolean) : []);

/** The authoring fields onto the library's (LibrarySkill in packages/agents/src/skill-library/types.ts). */
function mapSkill(f, body, where) {
  if (f.key.length < 3 || f.key.length > 48 || !/^[a-z0-9_]+$/.test(f.key)) throw new Error(`${where}: key is not 3 to 48 snake case characters: ${f.key}`);
  if (!GROUPS.includes(f.attribute_group)) throw new Error(`${where}: attribute_group is not one of ${GROUPS.join(", ")}: ${f.attribute_group}`);
  if (!f.when_to_use.startsWith("Use when")) throw new Error(`${where}: when_to_use does not start with "Use when"`);
  const stageSet = new Set();
  for (const s of list(f.stage)) {
    if (!STAGE_MAP[s]) throw new Error(`${where}: unknown stage ${s}`);
    for (const p of STAGE_MAP[s]) stageSet.add(p);
  }
  const requires = [];
  const notYet = [];
  for (const n of list(f.needs)) {
    const mapped = NEED_MAP[n];
    if (!mapped) throw new Error(`${where}: unknown need ${n}`);
    if (mapped.connector && !requires.includes(mapped.connector)) requires.push(mapped.connector);
    if (mapped.notYet && !notYet.includes(mapped.notYet)) notYet.push(mapped.notYet);
  }
  return {
    key: f.key,
    name: f.name,
    description: f.description,
    category: f.category,
    attribute: { name: f.attribute_name, group: f.attribute_group },
    whenToUse: f.when_to_use,
    roles: list(f.roles),
    defaultFor: list(f.default_for),
    // The release of the role defaults a skill joined (`default_since`, 1 when absent): an agent hired under an earlier
    // release receives it from the backfill.
    defaultSince: f.default_since ? Number(f.default_since) : 1,
    loadAlways: f.load === "always",
    stages: PRODUCT_STAGES.filter((p) => stageSet.has(p)),
    requires,
    notYetOnFoundmill: notYet,
    improves: list(f.improves),
    version: Number(f.version),
    body,
    provenance: provenanceOf(f.adapted_from, f.license_note, where),
  };
}

/**
 * `original` is Foundmill's own; `original, after ...` is Foundmill's own with what it was written after as the note;
 * anything else lists `collection:skill` sources (an `original` among them is dropped) and is adapted, under the first
 * license `license_note` names, with the whole `license_note` (its copyright lines) as the note.
 */
function provenanceOf(adaptedFrom, licenseNote, where) {
  if (adaptedFrom === "original") return { origin: "foundmill", sources: [], license: null, note: null };
  const after = /^original, (after .+)$/.exec(adaptedFrom);
  if (after) return { origin: "foundmill", sources: [], license: null, note: after[1] };
  const items = list(adaptedFrom).filter((x) => x !== "original");
  if (!items.length || !items.every((x) => SOURCE.test(x))) throw new Error(`${where}: adapted_from is not original, "original, after ..." or collection:skill sources: ${adaptedFrom}`);
  const license = LICENSE.exec(licenseNote)?.[1];
  if (!license) throw new Error(`${where}: an adapted skill names no license (MIT or Apache-2.0) in license_note`);
  return { origin: "adapted", sources: items, license, note: licenseNote };
}

/** Every skill under `skillsDir`, checked, in category order and then by key. Top-level files (a README) are skipped. */
export function readSkills(skillsDir, categories = categoriesFrom()) {
  const skills = [];
  const seen = new Map();
  for (const folder of readdirSync(skillsDir).sort()) {
    const dir = join(skillsDir, folder);
    if (!statSync(dir).isDirectory()) continue;
    for (const name of readdirSync(dir).sort()) {
      const where = `${folder}/${name}`;
      const { fields, body } = parseSkillSource(readFileSync(join(dir, name), "utf8"), where);
      if (!categories.includes(fields.category)) throw new Error(`${where}: unknown category ${fields.category}`);
      if (fields.category !== folder) throw new Error(`${where}: category ${fields.category} is not its folder ${folder}`);
      if (name !== `${fields.key}.md`) throw new Error(`${where}: file name is not ${fields.key}.md`);
      if (seen.has(fields.key)) throw new Error(`${where}: key ${fields.key} repeats ${seen.get(fields.key)}`);
      seen.set(fields.key, where);
      skills.push(mapSkill(fields, body, where));
    }
  }
  const rank = (s) => categories.indexOf(s.category);
  return skills.sort((a, b) => rank(a) - rank(b) || (a.key < b.key ? -1 : a.key > b.key ? 1 : 0));
}

/** The text of catalog.generated.ts for the skills under `skillsDir`. */
export function renderCatalog(skillsDir, categories = categoriesFrom()) {
  const s = JSON.stringify;
  const entries = readSkills(skillsDir, categories).map((k) =>
    [
      "  {",
      `    key: ${s(k.key)},`,
      `    name: ${s(k.name)},`,
      `    description: ${s(k.description)},`,
      `    category: ${s(k.category)},`,
      `    attribute: { name: ${s(k.attribute.name)}, group: ${s(k.attribute.group)} },`,
      `    whenToUse: ${s(k.whenToUse)},`,
      `    roles: ${s(k.roles)},`,
      `    defaultFor: ${s(k.defaultFor)},`,
      `    defaultSince: ${k.defaultSince},`,
      ...(k.loadAlways ? ["    loadAlways: true,"] : []),
      `    stages: ${s(k.stages)},`,
      `    requires: [${k.requires.map((c) => `{ connectorKey: ${s(c)}, mode: "better_with" }`).join(", ")}],`,
      `    notYetOnFoundmill: ${s(k.notYetOnFoundmill)},`,
      `    improves: ${s(k.improves)},`,
      `    version: ${k.version},`,
      `    instructionsMd: ${s(k.body)},`,
      `    provenance: { origin: ${s(k.provenance.origin)}, sources: ${s(k.provenance.sources)}, license: ${s(k.provenance.license)}, note: ${s(k.provenance.note)} },`,
      "  },",
    ].join("\n"),
  );
  return [
    HEADER,
    'import type { LibrarySkill } from "./types";',
    "",
    "export const SKILL_LIBRARY: readonly LibrarySkill[] = Object.freeze([",
    ...entries,
    "]);",
    "",
  ].join("\n");
}

function main(args) {
  const check = args.includes("--check");
  let text;
  try {
    text = renderCatalog(SKILLS_DIR);
  } catch (err) {
    console.error(`build-skill-library: ${err.message}`);
    return 1;
  }
  const rel = relative(ROOT, CATALOG_FILE);
  if (check) {
    if (!existsSync(CATALOG_FILE) || readFileSync(CATALOG_FILE, "utf8") !== text) {
      console.error(`build-skill-library: ${rel} is stale; run pnpm --filter @foundmill/agents skills:build`);
      return 1;
    }
    console.log(`${rel} is up to date.`);
    return 0;
  }
  writeFileSync(CATALOG_FILE, text);
  console.log(`Wrote ${rel}.`);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exit(main(process.argv.slice(2)));
